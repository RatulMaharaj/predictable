"""Render a `Report` as the published Markdown table."""

from __future__ import annotations

from .harness import Report
from .scenarios import CI_ONLY_SIZES, SCENARIOS


def _fmt_time(seconds: float) -> str:
    if seconds < 1e-3:
        return f"{seconds * 1e6:.0f} µs"
    if seconds < 1.0:
        return f"{seconds * 1e3:.1f} ms"
    return f"{seconds:.2f} s"


def _fmt_rate(rate: float) -> str:
    for unit, scale in (("G", 1e9), ("M", 1e6), ("k", 1e3)):
        if rate >= scale:
            return f"{rate / scale:.2f} {unit}"
    return f"{rate:.0f} "


def _fmt_size(n: int) -> str:
    return f"{n:,}"


def render(report: Report) -> str:
    lines: list[str] = []
    env = report.environment
    lines += [
        "# Benchmark results",
        "",
        "Generated by `python -m bench` in `benchmarks/`. Do not edit by hand.",
        "",
        "## Environment",
        "",
        "| | |",
        "|---|---|",
    ]
    for key in (
        "recorded_at", "platform", "processor", "logical_cpus", "python",
        "predictable", "numpy", "cashflower", "modelx", "git_commit",
    ):
        if env.get(key) is not None:
            lines.append(f"| {key} | {env[key]} |")

    lines += ["", "## The correctness gate", ""]
    lines.append(
        "Every engine is compared against the NumPy reference on every output it produces, "
        "for every modelpoint and every period. Tolerance: `1e-9`, scale-relative. "
        "No timing below was recorded until this table was clean."
    )
    lines += [
        "",
        "| scenario | M | engine | components | cells | worst component | worst error | verdict |",
        "|---|---:|---|---:|---:|---|---:|---|",
    ]
    for r in report.gate:
        if r.error:
            lines.append(
                f"| `{r.scenario}` | {_fmt_size(r.size)} | {r.engine} | — | — | — | — | "
                f"**error**: {r.error} |"
            )
            continue
        worst = r.worst
        verdict = "pass" if r.passed else "**FAIL**"
        lines.append(
            f"| `{r.scenario}` | {_fmt_size(r.size)} | {r.engine} | {len(r.components)} | "
            f"{sum(c.cells for c in r.components):,} | `{worst.component if worst else '—'}` | "
            f"{f'{worst.error:.2e}' if worst else '—'} | {verdict} |"
        )

    lines += ["", "## Wall time", ""]
    lines.append(
        "Median of the warm runs, with the cold run and the spread alongside. "
        "`mp-periods/s` is `M × (T + 1) / median` — the size-independent number."
    )
    lines += [
        "",
        "| scenario | M | engine | threads | cold | median | min–max | mp-periods/s "
        "| peak RSS | note |",
        "|---|---:|---|---:|---:|---:|---|---:|---:|---|",
    ]
    for t in sorted(report.timings, key=lambda x: (x.scenario, x.size, x.engine, x.threads)):
        if not t.ok:
            lines.append(
                f"| `{t.scenario}` | {_fmt_size(t.size)} | {t.engine} | {t.threads} | "
                f"— | — | — | — | — | {t.note} |"
            )
            continue
        j = t.to_json()
        lines.append(
            f"| `{t.scenario}` | {_fmt_size(t.size)} | {t.engine} | {t.threads} | "
            f"{_fmt_time(t.cold_s)} | {_fmt_time(t.median_s)} | "
            f"{_fmt_time(j['min_s'])}–{_fmt_time(j['max_s'])} | "
            f"{_fmt_rate(t.mp_periods_per_s)} | {t.peak_rss_mb:.0f} MB | {t.note or ''} |"
        )

    speedups = _speedups(report)
    if speedups:
        lines += ["", "## predictable relative to the other engines", ""]
        lines += [
            "| scenario | M | vs cashflower | vs modelx | vs NumPy |",
            "|---|---:|---:|---:|---:|",
        ]
        for (scenario, size), row in sorted(speedups.items()):
            cells = [
                f"{row[e]:.1f}×" if row.get(e) else "—"
                for e in ("cashflower", "modelx", "numpy")
            ]
            lines.append(
                f"| `{scenario}` | {_fmt_size(size)} | " + " | ".join(cells) + " |"
            )

    lines += ["", "## Not run", ""]
    lines.append(
        f"Sizes the spec asks for that this run does not cover: "
        f"{', '.join(_fmt_size(s) for s in CI_ONLY_SIZES)} — CI-only, see the docs page."
    )
    for note in report.skipped:
        lines.append(f"- {note}")
    for t in report.timings:
        if not t.ok:
            lines.append(
                f"- `{t.scenario}` at M = {_fmt_size(t.size)}, {t.engine}, "
                f"{t.threads} thread(s): {t.note}"
            )
    for scenario in SCENARIOS.values():
        absent = [e for e, cap in scenario.caps.items() if cap == 0]
        if absent:
            lines.append(f"- `{scenario.name}`: not implemented in {', '.join(absent)}")
    lines.append("")
    return "\n".join(lines)


def _speedups(report: Report) -> dict[tuple[str, int], dict[str, float]]:
    single = {
        (t.scenario, t.size, t.engine): t.median_s
        for t in report.timings
        if t.threads == 1 and t.ok
    }
    out: dict[tuple[str, int], dict[str, float]] = {}
    for (scenario, size, engine), seconds in single.items():
        if engine == "predictable":
            continue
        base = single.get((scenario, size, "predictable"))
        if base:
            out.setdefault((scenario, size), {})[engine] = seconds / base
    return out
